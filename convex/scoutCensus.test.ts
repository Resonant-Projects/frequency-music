import { convexTest } from "convex-test";
import { describe, expect, test } from "vite-plus/test";
import { api } from "./_generated/api";
import type { MutationCtx } from "./_generated/server";
import schema from "./schema";
import { modules } from "../harness/modules";

type Status = "known" | "experimental" | "provisional" | "deprecated";
type Relevance = "on" | "off" | "unreviewed";

async function domain(
  ctx: MutationCtx,
  name: string,
  status: Status = "known",
) {
  await ctx.db.insert("conceptDomains", {
    name,
    status,
    introducedBy: "system",
    createdAt: 1,
    updatedAt: 1,
  });
}

async function concept(
  ctx: MutationCtx,
  name: string,
  conceptDomain: string,
  missionRelevance: Relevance = "on",
  sources = 0,
) {
  await ctx.db.insert("concepts", {
    name,
    displayName: name,
    aliases: [],
    domain: conceptDomain,
    missionRelevance,
    mentionCount: sources,
    hypothesisCount: 0,
    createdAt: 1,
    updatedAt: 1,
  });
  for (let index = 0; index < sources; index++) {
    await ctx.db.insert("edges", {
      fromType: "source",
      fromId: `${name}-source-${index}`,
      toType: "concept",
      toId: name,
      relationship: "mentions",
      autoGenerated: true,
      createdBy: "system",
      createdAt: 1,
    });
  }
}

/**
 * Shaped like the live 2026-11-23 census: biofield 0/1, production 0/4,
 * geometry 2/5, mathematics 4/5, acoustics 6/3 were the five targets, while
 * synthesis evidence sat on concepts under `music-production` and math
 * evidence under `mathematical-music-theory`.
 */
async function seedLiveShapedCensus(ctx: MutationCtx) {
  for (const name of [
    "biofield",
    "production",
    "geometry",
    "mathematics",
    "acoustics",
    "theory",
    "psychoacoustics",
    "music-production",
    "mathematical-music-theory",
    "ml-audio-engineering",
  ]) {
    await domain(ctx, name);
  }
  await concept(ctx, "biofield coherence", "biofield");
  for (let index = 0; index < 4; index++) {
    await concept(ctx, `production seed ${index}`, "production");
  }
  for (let index = 0; index < 5; index++) {
    await concept(
      ctx,
      `geometry ${index}`,
      "geometry",
      "on",
      index < 2 ? 1 : 0,
    );
  }
  for (let index = 0; index < 5; index++) {
    await concept(
      ctx,
      `mathematics ${index}`,
      "mathematics",
      "on",
      index < 4 ? 1 : 0,
    );
  }
  for (let index = 0; index < 3; index++) {
    await concept(ctx, `acoustics ${index}`, "acoustics", "on", 2);
  }
  for (let index = 0; index < 3; index++) {
    await concept(ctx, `theory ${index}`, "theory", "on", index === 0 ? 4 : 3);
  }
  for (let index = 0; index < 4; index++) {
    await concept(ctx, `psychoacoustics ${index}`, "psychoacoustics", "on", 3);
  }
  for (const [name, sources] of [
    ["mixing", 6],
    ["dynamic range compression", 2],
    ["subtractive synthesis", 2],
    ["physical modeling synthesis", 2],
    ["karplus-strong algorithm", 1],
  ] as const) {
    await concept(ctx, name, "music-production", "on", sources);
  }
  await concept(ctx, "voice leading", "mathematical-music-theory", "on", 5);
  for (let index = 0; index < 15; index++) {
    await concept(ctx, `audio ml ${index}`, "ml-audio-engineering", "off", 1);
  }
}

describe("source scout sector census", () => {
  test("counts sector evidence held under a non-bootstrap registry domain", async () => {
    const t = convexTest(schema, modules);
    await t.run(async (ctx) => {
      await domain(ctx, "production");
      await domain(ctx, "music-production");
      await domain(ctx, "synthesis-dsp");
      await concept(ctx, "production seed", "production");
      await concept(
        ctx,
        "karplus-strong algorithm",
        "music-production",
        "on",
        1,
      );
      await concept(ctx, "digital waveguide", "synthesis-dsp", "on", 2);
    });
    const { thinDomains } = await t.query(api.correspondences.scoutTargets, {});
    expect(thinDomains[0]).toEqual({
      domain: "production",
      sectorMapping: "synthesis",
      onMissionConceptCount: 3,
      sourceCount: 3,
    });
  });

  test("samples on-mission concepts before the bounded per-domain take", async () => {
    const t = convexTest(schema, modules);
    await t.run(async (ctx) => {
      await domain(ctx, "production");
      for (let index = 0; index < 60; index++) {
        await concept(ctx, `old off-mission ${index}`, "production", "off");
      }
      await concept(ctx, "newer waveguide model", "production", "on", 1);
    });
    const { thinDomains } = await t.query(api.correspondences.scoutTargets, {});
    expect(thinDomains).toEqual([
      {
        domain: "production",
        sectorMapping: "synthesis",
        onMissionConceptCount: 1,
        sourceCount: 1,
      },
    ]);
  });

  test("never returns an off-mission domain as a thin target", async () => {
    const t = convexTest(schema, modules);
    await t.run(async (ctx) => {
      for (const name of [
        "biofield",
        "general-science",
        "theory",
        "acoustics",
      ]) {
        await domain(ctx, name);
      }
      await concept(ctx, "biofield coherence", "biofield");
      await concept(ctx, "general concept", "general-science");
      await concept(ctx, "just intonation", "theory", "on", 3);
      await concept(ctx, "room modes", "acoustics", "on", 1);
    });
    const { thinDomains } = await t.query(api.correspondences.scoutTargets, {});
    expect(thinDomains).toEqual([
      {
        domain: "acoustics",
        sectorMapping: "wave",
        onMissionConceptCount: 1,
        sourceCount: 1,
      },
      {
        domain: "theory",
        sectorMapping: "music",
        onMissionConceptCount: 1,
        sourceCount: 3,
      },
    ]);
  });

  test("a live-shaped census stops re-targeting served areas", async () => {
    const t = convexTest(schema, modules);
    await t.run(seedLiveShapedCensus);
    const { thinDomains } = await t.query(api.correspondences.scoutTargets, {});
    expect(thinDomains).toEqual([
      {
        domain: "geometry",
        sectorMapping: "geometry",
        onMissionConceptCount: 5,
        sourceCount: 2,
      },
      {
        domain: "acoustics",
        sectorMapping: "wave",
        onMissionConceptCount: 3,
        sourceCount: 6,
      },
      {
        domain: "mathematics",
        sectorMapping: "math",
        onMissionConceptCount: 6,
        sourceCount: 9,
      },
      {
        domain: "theory",
        sectorMapping: "music",
        onMissionConceptCount: 3,
        sourceCount: 10,
      },
      {
        domain: "psychoacoustics",
        sectorMapping: "psycho",
        onMissionConceptCount: 4,
        sourceCount: 12,
      },
    ]);
  });
});
